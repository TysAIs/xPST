"""The prose parity counts must agree with the generated ledger.

``docs/technical/rust-parity-ledger.md`` is generated by ``cargo xtask ledger
--write`` and gated by ``crates/xpst-cli/tests/parity_ledger.rs``, so the ledger
itself cannot drift. The prose that quotes it is hand-written and was ungated, and
it did drift: ``docs/technical/cli-parity-gates.md`` claimed 66 of 88 in its status
note and 61 of 88 in its re-derivation block while the ledger read 67, and
``crates/README.md`` claimed 22 remaining stubs while the ledger had 21.

These tests re-derive the number from the ledger on every run instead of comparing
against a hard-coded one, so a tranche that moves a row fails here until the prose is
updated with it. The tamper tests call the same helpers the real checks call, so a
helper that stops detecting a wrong number fails them too.
"""

from __future__ import annotations

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
LEDGER = REPO_ROOT / "docs" / "technical" / "rust-parity-ledger.md"
GATES = REPO_ROOT / "docs" / "technical" / "cli-parity-gates.md"
CRATES_README = REPO_ROOT / "crates" / "README.md"

# The ledger's own headline: "**67 of 88 leaf commands are implemented.**"
_LEDGER_HEADLINE_RE = re.compile(r"\*\*(\d+) of (\d+) leaf commands are implemented\.\*\*")

# "<N> of <M>" — an implemented-count claim, e.g. "the ledger now reads **67 of 88**".
# The lookarounds keep it off "88 − 61" and off a version-like "1.2 of 3".
_IMPLEMENTED_CLAIM_RE = re.compile(r"(?<![\w.])(\d+) of (\d+)(?![\w])")

# "<N> of the <M>" — a stub-count claim, e.g. "21 of the 88 leaf commands".
_STUB_CLAIM_RE = re.compile(r"(?<![\w.])(\d+) of the (\d+)(?![\w])")


def _ledger_counts() -> tuple[int, int]:
    """``(implemented, total)`` from the ledger's generated headline."""
    match = _LEDGER_HEADLINE_RE.search(LEDGER.read_text(encoding="utf-8"))
    assert match is not None, (
        f"{LEDGER.relative_to(REPO_ROOT)} lost its "
        "'**<N> of <M> leaf commands are implemented.**' headline; "
        "regenerate it with `cargo xtask ledger --write`"
    )
    return int(match.group(1)), int(match.group(2))


def _implemented_claim_problems(text: str, implemented: int, total: int) -> list[str]:
    """Every ``<N> of <M>`` claim in ``text`` that is not the ledger's count."""
    problems: list[str] = []
    for raw_claimed, raw_denominator in _IMPLEMENTED_CLAIM_RE.findall(text):
        claimed, denominator = int(raw_claimed), int(raw_denominator)
        if (claimed, denominator) != (implemented, total):
            problems.append(
                f"claims {claimed} of {denominator}, ledger says {implemented} of {total}"
            )
    return problems


def _stub_claim_problems(text: str, implemented: int, total: int) -> list[str]:
    """Every ``<N> of the <M>`` claim in ``text`` that is not the ledger's stub count."""
    stubs = total - implemented
    problems: list[str] = []
    for raw_claimed, raw_denominator in _STUB_CLAIM_RE.findall(text):
        claimed, denominator = int(raw_claimed), int(raw_denominator)
        if (claimed, denominator) != (stubs, total):
            problems.append(
                f"claims {claimed} of the {denominator}, ledger leaves {stubs} of {total} unported"
            )
    return problems


def test_ledger_headline_matches_its_own_rows() -> None:
    """The premise: the generated headline and the generated rows agree."""
    implemented, total = _ledger_counts()
    text = LEDGER.read_text(encoding="utf-8")

    implemented_rows = text.count("| implemented |")
    stub_rows = text.count("| stub |")

    assert implemented_rows == implemented, (
        f"ledger headline says {implemented} implemented, table has {implemented_rows} rows"
    )
    assert implemented_rows + stub_rows == total, (
        f"ledger headline says {total} leaves, table has {implemented_rows + stub_rows} rows"
    )


def test_cli_parity_gates_quotes_the_ledger_count() -> None:
    implemented, total = _ledger_counts()
    text = GATES.read_text(encoding="utf-8")

    assert _IMPLEMENTED_CLAIM_RE.findall(text), (
        "docs/technical/cli-parity-gates.md no longer quotes the ledger's count, so this "
        "guard would pass vacuously; restore the '**<N> of <M>**' claim"
    )

    problems = _implemented_claim_problems(text, implemented, total)

    assert problems == [], (
        "docs/technical/cli-parity-gates.md disagrees with "
        f"docs/technical/rust-parity-ledger.md ({implemented} of {total}):\n  - "
        + "\n  - ".join(problems)
    )


def test_crates_readme_quotes_the_ledger_stub_count() -> None:
    implemented, total = _ledger_counts()
    text = CRATES_README.read_text(encoding="utf-8")

    assert _STUB_CLAIM_RE.findall(text), (
        "crates/README.md no longer quotes the remaining-stub count, so this guard would "
        "pass vacuously; restore the '<N> of the <M> leaf commands' claim"
    )

    problems = _stub_claim_problems(text, implemented, total)

    assert problems == [], (
        "crates/README.md disagrees with "
        f"docs/technical/rust-parity-ledger.md ({implemented} of {total}):\n  - "
        + "\n  - ".join(problems)
    )


def test_a_stale_count_in_the_gates_doc_is_rejected() -> None:
    """The check must fail on a wrong number, not merely pass today.

    Derived from whatever the doc currently claims, so this test keeps working while
    the doc is being corrected — it exercises the checker, not the doc.
    """
    implemented, total = _ledger_counts()
    text = GATES.read_text(encoding="utf-8")
    match = _IMPLEMENTED_CLAIM_RE.search(text)
    assert match is not None, "docs/technical/cli-parity-gates.md quotes no count at all"

    claimed, denominator = int(match.group(1)), int(match.group(2))
    wrong = claimed + 1
    if (wrong, denominator) == (implemented, total):
        # The doc is already stale by one; pick a value that is wrong either way.
        wrong += 1
    tampered = text[: match.start()] + f"{wrong} of {denominator}" + text[match.end() :]

    problems = _implemented_claim_problems(tampered, implemented, total)

    assert any(f"claims {wrong} of {denominator}" in problem for problem in problems), problems


def test_a_stale_stub_count_in_crates_readme_is_rejected() -> None:
    implemented, total = _ledger_counts()
    text = CRATES_README.read_text(encoding="utf-8")
    match = _STUB_CLAIM_RE.search(text)
    assert match is not None, "crates/README.md quotes no remaining-stub count at all"

    claimed, denominator = int(match.group(1)), int(match.group(2))
    wrong = claimed + 1
    if (wrong, denominator) == (total - implemented, total):
        # The doc is already stale by one; pick a value that is wrong either way.
        wrong += 1
    tampered = text[: match.start()] + f"{wrong} of the {denominator}" + text[match.end() :]

    problems = _stub_claim_problems(tampered, implemented, total)

    assert any(f"claims {wrong} of the {denominator}" in problem for problem in problems), problems
