#!/usr/bin/env python3
"""Capture the wizard's per-platform guide table and its markdown export.

`xpst wizard --json` carries a `checklist` built from `xpst.wizard.PLATFORM_GUIDES`
(eight platforms of prose), and `xpst wizard --export-md` renders the same table
as markdown. Both are static data, so the Rust engine holds them as a captured
resource instead of a hand-transcribed table — a hand port of 40-odd sentences
would drift on the first typo and nothing would notice.

    PYTHONPATH=src XPST_PYTHON=<venv>/bin/python python xtask/scripts/capture_wizard_guides.py

Writes:

* `crates/xpst-cli/src/resources/wizard_guides.json` — the table, in
  `GUIDE_PLATFORMS` order, plus `OPT_IN_PLATFORMS`;
* `crates/xpst-cli/tests/fixtures/wizard_export.md` — the exact bytes
  `export_markdown()` writes, so the Rust renderer is held to the shipped file
  rather than to a reading of the renderer.

Re-running must reproduce both byte-for-byte; the script asserts that itself.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RESOURCE = REPO / "crates/xpst-cli/src/resources/wizard_guides.json"
EXPORT_FIXTURE = REPO / "crates/xpst-cli/tests/fixtures/wizard_export.md"


def main() -> int:
    sys.path.insert(0, str(REPO / "src"))
    from xpst.wizard import (  # noqa: PLC0415 - after sys.path
        GUIDE_PLATFORMS,
        OPT_IN_PLATFORMS,
        PLATFORM_GUIDES,
        export_markdown,
    )

    guides = {}
    for key in GUIDE_PLATFORMS:
        guide = PLATFORM_GUIDES[key]
        guides[key] = {
            "key": guide.key,
            "title": guide.title,
            "why": guide.why,
            "steps": [step.text for step in guide.steps],
            "docs_url": guide.docs_url,
        }

    document = {
        "captured_from": "src/xpst/wizard.py",
        "note": (
            "Generated by xtask/scripts/capture_wizard_guides.py; never edit by hand. "
            "`guide_platforms` is GUIDE_PLATFORMS order (the order the checklist and the "
            "markdown export iterate), not alphabetical."
        ),
        "guide_platforms": list(GUIDE_PLATFORMS),
        "opt_in_platforms": list(OPT_IN_PLATFORMS),
        "guides": guides,
    }

    if not guides:
        raise SystemExit("captured no guides — refusing to write an empty resource")

    RESOURCE.parent.mkdir(parents=True, exist_ok=True)
    RESOURCE.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    EXPORT_FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    export_markdown(EXPORT_FIXTURE)

    # Reproducibility: a second render must be byte-identical to the first.
    second = EXPORT_FIXTURE.with_suffix(".md.second")
    export_markdown(second)
    if second.read_bytes() != EXPORT_FIXTURE.read_bytes():
        raise SystemExit("export_markdown is not reproducible")
    second.unlink()

    print(f"wrote {RESOURCE.relative_to(REPO)} ({len(guides)} guides)")
    print(f"wrote {EXPORT_FIXTURE.relative_to(REPO)} ({EXPORT_FIXTURE.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
