//! The generated parity ledger: one row per leaf command.
//!
//! The ledger is a rendering of three checked-in facts and nothing else:
//!
//! * the command list, from the parity manifest (`parity::manifest()`);
//! * which commands have behaviour, from [`crate::implemented::IMPLEMENTED`];
//! * whether the Python path calls the network, from
//!   `parity/python_network.json`.
//!
//! That is what makes the doc trustworthy: `dispatch` reads the same table, so a
//! command cannot be implemented without a row, and a row cannot claim an
//! implementation that does not exist. `tests/parity_ledger.rs` fails when the
//! committed file differs from this rendering.
//!
//! The owner column is the *port map* answer, not a claim about the code today:
//! `docs/PROPOSAL-RUST-REBUILD.md` §3 assigns each Python module to a crate, and
//! a stub's owner is where its behaviour is planned to land. The doc says so.

use crate::implemented::IMPLEMENTED;
use crate::parity;

/// The ledger's path, relative to the repository root.
pub const LEDGER_PATH: &str = "docs/technical/rust-parity-ledger.md";

/// Crate that owns a command's behaviour, per the proposal's port map.
///
/// Grouped by the Python module the command's implementation lives in; see
/// `docs/PROPOSAL-RUST-REBUILD.md` §3.
pub fn owner_for(path: &str) -> &'static str {
    let head = path.split(' ').next().unwrap_or("");
    match head {
        "analytics" | "best-time" => "xpst-store",
        "app" => "xpst-app",
        "auth" | "connect" | "disconnect" | "refresh-tokens" | "devices" | "pair" | "byo"
        | "setup" | "wizard" | "onboard" => "xpst-auth",
        "backfill" | "post" | "run" | "watch" | "preflight" | "delete" | "serve" => "xpst-core",
        "capabilities" | "providers" | "health" | "stream" | "chat" | "messenger" | "followers" => {
            "xpst-provider"
        }
        "config" => "xpst-config",
        "dashboard" | "ui" => "xpst-api",
        "kb" | "search" | "transcript" => "xpst-store",
        "mcp" => "xpst-mcp",
        "media" | "verify-media" => "xpst-media",
        "generate" | "suggest-caption" => "xpst-core",
        "failures" => {
            if path == "failures retry" {
                "xpst-core"
            } else {
                "xpst-state"
            }
        }
        "schedule" => {
            if path == "schedule run" {
                "xpst-core"
            } else {
                "xpst-state"
            }
        }
        "state" | "quota" | "status" => "xpst-state",
        _ => "xpst-cli",
    }
}

/// Leaf command paths: paths no other command extends.
pub fn leaves() -> Vec<String> {
    let all: Vec<Vec<String>> = parity::manifest()
        .commands
        .iter()
        .map(|command| command.path.clone())
        .collect();
    let mut leaves: Vec<String> = parity::manifest()
        .commands
        .iter()
        .filter(|command| !command.path.is_empty())
        .filter(|command| {
            !all.iter().any(|other| {
                other.len() > command.path.len() && other[..command.path.len()] == command.path[..]
            })
        })
        .map(|command| command.path.join(" "))
        .collect();
    leaves.sort();
    leaves
}

/// Group command paths: containers whose bare invocation prints help.
pub fn groups() -> Vec<String> {
    let all: Vec<Vec<String>> = parity::manifest()
        .commands
        .iter()
        .map(|command| command.path.clone())
        .collect();
    let mut groups: Vec<String> = parity::manifest()
        .commands
        .iter()
        .filter(|command| !command.path.is_empty())
        .filter(|command| {
            all.iter().any(|other| {
                other.len() > command.path.len() && other[..command.path.len()] == command.path[..]
            })
        })
        .map(|command| command.path.join(" "))
        .collect();
    groups.sort();
    groups
}

/// Render the ledger document.
pub fn render() -> String {
    let leaves = leaves();

    let implemented: Vec<&str> = IMPLEMENTED.iter().map(|entry| entry.path).collect();
    let mut text = String::new();
    text.push_str("# Rust engine parity ledger\n\n");
    text.push_str(
        "<!-- Generated by `cargo xtask ledger --write`; do not edit by hand. \
         `crates/xpst-cli/tests/parity_ledger.rs` fails when this file and the \
         engine disagree. -->\n\n",
    );
    text.push_str(
        "One row per leaf command of the shipped CLI. `status` is `implemented` when the \
         Rust engine runs the command and `stub` when it answers `not implemented in the \
         Rust engine yet`. The two columns either side are the questions a reader \
         actually has: which crate owns the behaviour, and whether the Python \
         implementation they are comparing against makes an outbound network call.\n\n",
    );
    text.push_str(&format!(
        "**{} of {} leaf commands are implemented.** The rest parse their arguments \
         exactly as the Python CLI does and exit {} (`NOT_IMPLEMENTED`, documented as \
         `EXIT_GENERAL`). The {} group commands ({}) are containers: a bare invocation \
         prints help in both engines, which `crates/xpst-cli/tests/parity.rs` covers.\n\n",
        implemented.len(),
        leaves.len(),
        crate::exit::NOT_IMPLEMENTED,
        groups().len(),
        groups()
            .iter()
            .map(|path| format!("`{path}`"))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    text.push_str(
        "## Columns\n\n\
         * **Owner crate** — where the behaviour lives, or where the port map \
         (`docs/PROPOSAL-RUST-REBUILD.md` §3) plans to put it while it is a stub. A stub's \
         owner is a plan, not a claim.\n\
         * **Python network** — `none` when the shipped Python path only reads local files \
         (audited; the evidence is in `crates/xpst-cli/src/parity/python_network.json`), \
         `yes` when it contacts a platform or provider API on every run that does its job, \
         and `possible` when that depends on arguments or configuration. It is a reviewed \
         judgement with the deciding call named, not a runtime capture.\n\n",
    );

    text.push_str("## Ledger\n\n");
    text.push_str("| Command | Rust status | Owner crate | Python network |\n");
    text.push_str("|---|---|---|---|\n");
    for path in &leaves {
        let status = if implemented.contains(&path.as_str()) {
            "implemented"
        } else {
            "stub"
        };
        let network = parity::network_for(path)
            .map(|entry| entry.network.as_str())
            .unwrap_or("unknown");
        // An implemented command's owner is the engine table's answer; the
        // port-map rule is only a plan for the stubs.
        let owner = IMPLEMENTED
            .iter()
            .find(|entry| entry.path == path.as_str())
            .map(|entry| entry.owner)
            .unwrap_or_else(|| owner_for(path));
        text.push_str(&format!("| `{path}` | {status} | {owner} | {network} |\n"));
    }

    text.push_str("\n## Implemented commands\n\n");
    text.push_str("| Command | Owner crate | What was verified |\n|---|---|---|\n");
    for entry in IMPLEMENTED {
        text.push_str(&format!(
            "| `{}` | {} | {} |\n",
            entry.path, entry.owner, entry.note
        ));
    }

    text.push_str(
        "\n## Known deviations from the Python engine\n\n\
         Named on purpose: a difference that is not written down is a bug nobody found.\n\n",
    );
    for line in DEVIATIONS {
        text.push_str(&format!("* {line}\n"));
    }
    text
}

